import assert from 'node:assert/strict';
import fs from 'node:fs';
const { buildTabTree, validParent, descendants } = await import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync(new URL('../src/tab-tree.js', import.meta.url))).toString('base64'));
const tabs = [1,2,3,4].map((id,index)=>({id,index,windowId:1,groupId:10,pinned:false}));
const rt={groupSpace:{10:'main'},tabPin:{},tabParent:{2:1,3:2},treeCollapsed:{}};
let tree=buildTabTree(tabs,rt,'main');
assert.deepEqual(tree.rows.map(e=>[e.tab.id,e.depth]),[[1,0],[2,1],[3,2],[4,0]]);
assert.deepEqual(descendants(1,rt.tabParent),[2,3]);
rt.treeCollapsed['main:1']=true;
assert.deepEqual(buildTabTree(tabs,rt,'main').rows.map(e=>e.tab.id),[1,4]);
assert.equal(tree.info(1).childCount,2);
rt.tabPin[1]='wiki';
tree=buildTabTree(tabs,rt,'main');assert.deepEqual(tree.rows.map(e=>e.tab.id),[4]);
assert.equal(validParent(tabs[1],tabs[0],rt),true);
assert.equal(validParent({...tabs[1],windowId:2},tabs[0],rt),false);
assert.equal(validParent({...tabs[1],groupId:11},tabs[0],rt),false);
assert.equal(validParent(tabs[1],{...tabs[0],pinned:true},rt),true);
assert.equal(validParent(tabs[0],tabs[1],rt),false);
rt.tabPin={};rt.tabParent={1:3,2:1,3:2};
assert.equal(buildTabTree(tabs,rt,'main').rows.length,4);
console.log('PASS tab-tree depth, collapse, counts, pinned roots, window/space guards, and cycle-safe rendering');
