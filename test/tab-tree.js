(async () => {
  const log=[];
  const ok=(pass,label)=>{log.push(`${pass?'PASS':'FAIL'} ${label}`);console.log(log.at(-1));};
  const sleep=ms=>new Promise(r=>setTimeout(r,ms));
  const wait=async f=>{for(let i=0;i<100;i++){if(await f())return;await sleep(60);}throw new Error('Timed out waiting for tree state');};
  const send=async(type,args={})=>{const r=await chrome.runtime.sendMessage({type,...args});if(!r.ok)throw new Error(r.error);return r.result;};
  const rt=async()=> (await chrome.storage.session.get('rt')).rt;
  const cfg=async()=> (await chrome.storage.local.get('config')).config;
  const row=id=>document.querySelector(`.row[data-kind=tab][data-id="${id}"]`);
  try {
    const W=(await chrome.windows.getCurrent()).id;
    const control=(await chrome.tabs.getCurrent()).id;
    await send('pinTab',{tabId:control,spaceId:null});
    const main=(await cfg()).spaces[0].id;
    const root=await send('newTab',{windowId:W,spaceId:main,url:'__BASE__/Wikipedia'});
    await wait(async()=> (await chrome.tabs.get(root)).status==='complete');
    const make=async(opener,path)=>{
      await wait(async()=> (await chrome.tabs.get(opener)).status==='complete');
      const url='__BASE__/'+path;
      await chrome.scripting.executeScript({target:{tabId:opener},func:url=>{const a=document.createElement('a');a.href=url;a.target='_blank';a.rel='noopener';document.body.append(a);a.click();a.remove();},args:[url]});
      let child;
      await wait(async()=>{child=(await chrome.tabs.query({windowId:W})).find(t=>t.url===url||t.pendingUrl===url);return child && (await rt()).tabParent[child.id]===opener;});
      return child.id;
    };
    const article=await make(root,'Article');
    const detail=await make(article,'Related-article');
    const sibling=await make(root,'Another-article');
    const signed=await make(root,'Signed-link?code=tree-secret#access_token=tree-token');
    const savedTree=(await chrome.storage.local.get('tabTreeState')).tabTreeState;
    ok(!JSON.stringify(savedTree).includes('tree-secret') && !JSON.stringify(savedTree).includes('tree-token'),'tree persistence redacts sensitive URL tokens');
    await send('closeTabs',{windowId:W,tabIds:[signed]});
    await chrome.tabs.update(control,{active:true});
    await wait(()=>row(detail));
    ok(row(root).style.getPropertyValue('--tree-depth')==='0' && row(article).style.getPropertyValue('--tree-depth')==='1' && row(detail).style.getPropertyValue('--tree-depth')==='2','link-opened tabs form a nested tree with visible depth');
    row(root).querySelector('.tree-toggle').click();
    await wait(()=>!row(article));
    ok(!row(detail) && !!row(root),'collapsing a parent hides its descendant rows without closing tabs');
    await chrome.tabs.update(detail,{active:true});
    await wait(()=>row(detail)?.classList.contains('active'));
    ok(!!row(article),'selecting a hidden descendant reveals its ancestors');
    const blankChild=await send('newChildTab',{tabId:root});
    await wait(async()=> (await rt()).tabParent[blankChild]===root);
    ok(/newtab/.test((await chrome.tabs.get(blankChild)).pendingUrl || (await chrome.tabs.get(blankChild)).url),'New child tab opens the native New Tab under its parent');
    await send('closeTabs',{windowId:W,tabIds:[blankChild]});
    const rejected=await chrome.runtime.sendMessage({type:'setTabParent',tabId:root,parentId:detail});
    ok(!rejected.ok && !(await rt()).tabParent[root],'cycles are rejected before changing the tree');
    await send('closeTabs',{windowId:W,tabIds:[article]});
    await wait(async()=> (await rt()).tabParent[detail]===root);
    ok(!!(await chrome.tabs.get(detail)),'closing a parent keeps children open one level up');
    await chrome.tabs.update(control,{active:true});
    await wait(()=>row(detail)&&row(sibling));
    const transfer=new DataTransfer();
    row(detail).dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer}));
    const rect=row(sibling).getBoundingClientRect();
    row(sibling).dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer,clientX:rect.left+70,clientY:rect.top+rect.height/2}));
    await wait(async()=> (await rt()).tabParent[detail]===sibling);
    ok(true,'dropping a tab inside another row reparents it');
    await send('setTabParent',{tabId:detail,parentId:null});
    ok((await rt()).treeDetached[detail] && !(await rt()).tabParent[detail],'tabs can be moved out to the root');
    const folder=await send('createFolder',{spaceId:main,name:'Reference'});
    await send('pinTab',{tabId:root,spaceId:main,folderId:folder});
    const pinId=(await rt()).tabPin[root];
    await wait(()=>document.querySelector(`#pins [data-kind=tab][data-id="${sibling}"]`));
    ok(!document.querySelector(`#tabs [data-kind=tab][data-id="${sibling}"]`),'children of a space pin render under it inside its folder');
    await send('updateFolder',{folderId:folder,collapsed:true});
    await wait(()=>!row(sibling));
    await chrome.tabs.update(sibling,{active:true});
    await wait(()=>row(sibling)?.classList.contains('active'));
    ok(!(await cfg()).folders[folder].collapsed,'selecting a pin child reveals the containing folder');
    await send('unloadPin',{windowId:W,pinId});
    await wait(async()=> !(await rt()).tabParent[sibling]);
    ok(!!(await chrome.tabs.get(sibling)),'unloading a pinned parent preserves its children');
    const essential=await send('newTab',{windowId:W,spaceId:main,url:'__BASE__/Essential-origin'});
    await wait(async()=> (await chrome.tabs.get(essential)).status==='complete');
    await send('pinTab',{tabId:essential,spaceId:null});
    const essentialChild=await make(essential,'Essential-child');
    await chrome.tabs.update(control,{active:true});
    await wait(()=>document.querySelector(`#tabs .tree-root[data-id="${essential}"]`) && row(essentialChild));
    ok(row(essentialChild).style.getPropertyValue('--tree-depth')==='1','Essential links appear under a per-space origin header');
    const restorable=await make(essential,'Essential-restored-child');
    await chrome.tabs.remove(restorable);
    await wait(async()=> (await chrome.storage.local.get('archive')).archive.some(entry=>entry.tabId===restorable));
    await send('undoArchive',{windowId:W});
    const reopenedEssentialChild=(await chrome.tabs.query({windowId:W})).find(t=>(t.url||t.pendingUrl)==='__BASE__/Essential-restored-child');
    ok(reopenedEssentialChild && (await rt()).tabParent[reopenedEssentialChild.id]===essential,'Undo of a native close restores a child under its live Essential parent');
    const other=await send('createSpace',{name:'Other'});
    const alien=await send('newTab',{windowId:W,spaceId:other,url:'__BASE__/Other-space'});
    const invalid=await chrome.runtime.sendMessage({type:'setTabParent',tabId:alien,parentId:detail});
    ok(!invalid.ok,'cross-space parent relationships are rejected');
    const clearSpace=await send('createSpace',{name:'Tree moves'});
    const moving=await send('newTab',{windowId:W,spaceId:clearSpace,url:'__BASE__/Moving-parent'});
    const keptChild=await make(moving,'Kept-child');
    await chrome.tabs.update(keptChild,{active:true});
    await send('moveTab',{tabId:moving,spaceId:other});
    ok(!(await rt()).tabParent[keptChild],'moving a parent to another space detaches children that stay behind');
    const disposable=await send('newTab',{windowId:W,spaceId:clearSpace,url:'__BASE__/Disposable'});
    await chrome.tabs.update(keptChild,{active:true});
    await send('clearSpace',{windowId:W,spaceId:clearSpace});
    ok(!!(await chrome.tabs.get(keptChild)) && !(await chrome.tabs.get(disposable).catch(()=>null)),'Clear still preserves the selected tree tab');
    await send('switchSpace',{windowId:W,spaceId:main});
    const branch=await send('newTab',{windowId:W,spaceId:main,url:'__BASE__/Undo-parent'});
    const leaf=await make(branch,'Undo-child');
    await send('closeTabs',{windowId:W,tabIds:[branch,leaf]});
    const restoredCount=await send('undoArchive',{windowId:W});
    const reopened=await chrome.tabs.query({windowId:W});
    const restored=['Undo-parent','Undo-child'].map(path=>reopened.find(t=>t.url==='__BASE__/'+path || t.pendingUrl==='__BASE__/'+path)?.id);
    ok(restoredCount===2 && (await rt()).tabParent[restored[1]]===restored[0],'undo restores archived parent/child relationships in a batch');
    await wait(async()=> (await Promise.all(restored.map(id=>chrome.tabs.get(id)))).every(t=>t.status==='complete'));
    await chrome.tabs.update(essential,{active:true});
    await wait(async()=> (await rt()).mru[W][0]===essential);
    const collapsedParent=restored[0];
    await send('toggleTabTree',{windowId:W,tabId:collapsedParent,spaceId:main});
    await chrome.storage.local.set({__tabTreeExpect:{detail,collapsedParent,leaf:restored[1],essential,essentialChild,main}});
    ok(true,'tree persistence fixture saved');
  } catch(error){log.push('FAIL '+error.stack);}
  return log.join('\n');
})()
