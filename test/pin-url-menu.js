(async () => {
  const notes=[];
  const ok=(condition,message)=>{notes.push(`${condition?'PASS':'FAIL'} ${message}`);};
  const pause=ms=>new Promise(r=>setTimeout(r,ms));
  const wait=async predicate=>{for(let i=0;i<100;i++){if(await predicate())return;await pause(60);}throw new Error('Timeout');};
  const send=async(type,args={})=>{const r=await chrome.runtime.sendMessage({type,...args});if(!r.ok)throw new Error(r.error);return r.result;};
  const cfg=async()=> (await chrome.storage.local.get('config')).config;
  const runtime=async()=> (await chrome.storage.session.get('rt')).rt;
  const windowId=(await chrome.windows.getCurrent()).id;
  const controlTabId=(await chrome.tabs.getCurrent()).id;
  const main=(await cfg()).spaces[0].id;
  const parent=await send('createFolder',{spaceId:main,name:'Parent'});
  const folder=await send('createFolder',{spaceId:main,parentId:parent,name:'Nested'});
  let id=await send('newTab',{windowId,spaceId:main,url:'__BASE__/menu-home'});
  await wait(async()=> (await chrome.tabs.get(id)).status==='complete');
  await send('pinTab',{tabId:id,spaceId:main,folderId:folder});
  await chrome.tabs.update(controlTabId,{active:true});
  const pinId=(await runtime()).tabPin[id];
  await send('renamePin',{pinId,title:'Review pin'});
  await chrome.tabs.update(id,{url:'__BASE__/different-page'});
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/different-page' && (await chrome.tabs.get(id)).status==='complete');
  await wait(()=>document.querySelector(`[data-kind=pin][data-id="${pinId}"]`));
  const openMenu=()=>document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:30,clientY:180}));
  await wait(()=> document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).title.includes('different-page') || document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  openMenu();
  const action=[...document.querySelectorAll('#menu .item')].find(n=>n.textContent.includes('Replace pinned URL with current'));
  ok(!!action,'Replace pinned URL with current is available after ordinary navigation');
  action?.click();
  await wait(async()=> (await cfg()).pins[pinId].url==='__BASE__/different-page');
  ok((await cfg()).pins[pinId].folderId===folder && (await cfg()).pins[pinId].title==='Review pin','replacing a URL preserves nested folder membership and custom name');
  await send('setPinUrl',{pinId,url:'__BASE__/app#/dashboard'});
  await chrome.tabs.update(id,{url:'__BASE__/app#/dashboard'});
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/app#/dashboard' && (await chrome.tabs.get(id)).status==='complete');
  await wait(()=>!document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  await chrome.tabs.update(id,{url:'__BASE__/app#/reports'});
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/app#/reports');
  await wait(()=>document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  openMenu();
  const replaceHash=[...document.querySelectorAll('#menu .item')].find(n=>n.textContent.includes('Replace pinned URL with current'));
  ok(!!replaceHash,'hash-route navigation exposes Replace pinned URL with current');
  replaceHash?.click();
  await wait(async()=> (await cfg()).pins[pinId].url==='__BASE__/app#/reports');
  ok((await cfg()).pins[pinId].folderId===folder && (await cfg()).pins[pinId].title==='Review pin','saving a hash route keeps the correct pin, custom name, and folder');
  await wait(()=>!document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  await chrome.tabs.update(id,{url:'__BASE__/app#/dashboard'});
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/app#/dashboard');
  await wait(()=>document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  openMenu();
  const reset=[...document.querySelectorAll('#menu .item')].find(n=>n.textContent.includes('Go back to pinned URL'));
  ok(!!reset,'hash-route navigation exposes Go back to pinned URL');
  reset?.click();
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/app#/reports');
  ok(true,'Go back restores the saved hash route');
  await chrome.tabs.update(controlTabId,{active:true});
  await send('unloadPin',{windowId,pinId});
  await send('openPin',{windowId,pinId});
  await chrome.tabs.update(controlTabId,{active:true});
  id=Number(Object.entries((await runtime()).tabPin).find(([,pid])=>pid===pinId)[0]);
  await wait(async()=> (await chrome.tabs.get(id)).status==='complete');
  await chrome.tabs.update(id,{url:'__BASE__/app#/quick-navigation'});
  await wait(async()=> (await chrome.tabs.get(id)).url==='__BASE__/app#/quick-navigation');
  await wait(()=>document.querySelector(`[data-kind=pin][data-id="${pinId}"]`).classList.contains('drifted'));
  openMenu();
  ok([ ...document.querySelectorAll('#menu .item')].some(n=>n.textContent.includes('Replace pinned URL with current')),'quick hash navigation after reopening is not hidden by redirect settling');
  ok(!(await cfg()).pins[pinId].aliases.some(url=>url.endsWith('#/quick-navigation')),'hash navigation is not stored as a redirect alias');
  return notes.join('\n');
})()
